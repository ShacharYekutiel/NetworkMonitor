"""[2b-2] OUI vendor lookup from the bundled IEEE MA-L listing (`netmon/data/oui.tsv.gz`,
generated by `backend/scripts/update_oui.py`). Loaded lazily once per process; never downloaded
at runtime."""

from __future__ import annotations

import gzip
import logging
import threading
from pathlib import Path

from netmon.ports.collect import locally_administered

log = logging.getLogger("netmon.ports.oui")

DATA_FILE = Path(__file__).resolve().parent.parent / "data" / "oui.tsv.gz"

_table: dict[str, str] | None = None
_lock = threading.Lock()


def load(path: Path = DATA_FILE) -> dict[str, str]:
    out: dict[str, str] = {}
    try:
        with gzip.open(path, "rt", encoding="utf-8") as f:
            for line in f:
                if not line or line.startswith("#"):
                    continue
                prefix, _, name = line.rstrip("\n").partition("\t")
                if len(prefix) == 6 and name:
                    out[prefix.upper()] = name
    except OSError as exc:
        log.warning("Cannot read the OUI table %s: %s", path, exc)
    return out


def table() -> dict[str, str]:
    global _table
    if _table is None:
        with _lock:
            if _table is None:
                _table = load()
    return _table


def vendor(mac: str | None) -> str | None:
    """Organisation of the MAC's first 3 octets; None when unknown or locally administered."""
    if not mac:
        return None
    hexdigits = "".join(ch for ch in mac if ch.isalnum()).upper()
    if len(hexdigits) < 6 or locally_administered(hexdigits[:2] + ":"):
        return None
    return table().get(hexdigits[:6])
