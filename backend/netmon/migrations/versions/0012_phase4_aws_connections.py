"""[4] P4-1 — shared AWS connections (PR 4-0a; architecture § 15.1.4, data-model § [4] "AWS
connections (migration P4-1)").

The revision number is the next free one on this branch and is re-assigned when the PR merges
(release 1.4.2 adds its own migration in parallel): `revision` / `down_revision` below are the
ONLY place the number is written (tests find this migration by `PLACEHOLDER = "P4-1"`).

upgrade (plain SQL, idempotent):
1. `aws_connections` + the partial unique index `aws_connections_one_default`;
2. when the `assistant` settings row holds any authentication value: insert "Default"
   (`is_default`, `aad_scope = 'assistant'`, the auth keys and ciphertexts copied verbatim —
   their AADs `assistant.<field>` stay valid, so no re-encryption and no `secret.key` here;
   `region` = `ra_region` or `region`; `ra_endpoint_url` → override (rolesanywhere, region))
   and set `assistant.connection_id` / `access`; otherwise no row;
3. the legacy authentication keys of `assistant` are NOT removed (container rollback, § 15.1.9).

downgrade: remove `connection_id` / `access` from `assistant`, drop the table. Refused when a
connection other than the `aad_scope = 'assistant'` row exists or the assistant uses another
connection or a hop, unless NETMON_FORCE_DOWNGRADE=1 (the legacy keys then hold the last
mirrored state).

Revision ID: 0012
Revises: 0011
Create Date: 2026-11-13
"""

