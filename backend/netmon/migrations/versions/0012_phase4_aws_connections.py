# the 1.4.x auth keys copied into `settings` (ra_region / ra_endpoint_url / proxy handled apart)
SETTINGS_KEYS = (
    "access_key_id",
    "secret_access_key_enc",
    "session_token_enc",
    "access_key_created_at",
    "ra_trust_anchor_arn",
    "ra_profile_arn",
    "ra_role_arn",
    "ra_session_seconds",
    "ra_cert_pem",
    "ra_chain_pem",
    "ra_key_enc",
    "ra_cert_uploaded_at",
    "ra_csr_pem",
    "ra_csr_key_enc",
    "ra_csr_subject",
    "ra_csr_created_at",
)
AUTH_MARKERS = (
    "access_key_id",
    "secret_access_key_enc",
    "ra_trust_anchor_arn",
    "ra_cert_pem",
    "ra_csr_pem",
)
DIRECT = {"mode": "direct", "role_arn": None, "external_id": None}


def _assistant(bind):  # type: ignore[no-untyped-def]
    row = bind.execute(sa.text("SELECT value FROM settings WHERE key = 'assistant'")).first()
    if row is None:
        return None
    value = row[0]
    if isinstance(value, str):
        value = json.loads(value)
    return value if isinstance(value, dict) else None


def _has_auth(a: dict) -> bool:
    return a.get("auth_mode") == "default_chain" or any(a.get(k) for k in AUTH_MARKERS)


def upgrade() -> None:
    for stmt in UPGRADE:
        op.execute(stmt)
    bind = op.get_bind()
    a = _assistant(bind)
    if a is None or not _has_auth(a):
        return
    existing = bind.execute(
        sa.text("SELECT id FROM aws_connections WHERE aad_scope = 'assistant'")
    ).first()
    if existing is not None:  # idempotent: already moved
        conn_id = int(existing[0])
    else:
        region = (a.get("ra_region") or "") or a.get("region") or "us-east-1"
        overrides = []
        if a.get("ra_endpoint_url"):
            overrides.append(
                {"service": "rolesanywhere", "region": region, "url": a["ra_endpoint_url"]}
            )
        settings = {k: a.get(k) for k in SETTINGS_KEYS if k in a}
        settings["ra_region"] = None  # now equals the connection region
        if settings.get("ra_session_seconds") is None:
            settings["ra_session_seconds"] = 3600
        has_default = bind.execute(
            sa.text("SELECT 1 FROM aws_connections WHERE is_default")
        ).first()
        conn_id = int(
            bind.execute(
                sa.text(
                    "INSERT INTO aws_connections (name, is_default, auth_mode, region, "
                    "proxy_mode, proxy_url, endpoint_overrides, settings, aad_scope) VALUES "
                    "(:name, :d, :auth, :region, :pm, :pu, CAST(:eo AS jsonb), "
                    "CAST(:s AS jsonb), 'assistant') RETURNING id"
                ),
                {
                    "name": "Default",
                    "d": has_default is None,
                    "auth": a.get("auth_mode") or "roles_anywhere",
                    "region": region,
                    "pm": a.get("proxy_mode") or "env",
                    "pu": a.get("proxy_url"),
                    "eo": json.dumps(overrides),
                    "s": json.dumps(settings),
                },
            ).scalar_one()
        )
    if "connection_id" not in a or "access" not in a:
        bind.execute(
            sa.text(
                "UPDATE settings SET value = value || CAST(:extra AS jsonb) WHERE key = 'assistant'"
            ),
            {"extra": json.dumps({"connection_id": conn_id, "access": DIRECT})},
        )


def downgrade() -> None:
    bind = op.get_bind()
    force = os.environ.get("NETMON_FORCE_DOWNGRADE") == "1"
    a = _assistant(bind) or {}
    table = bind.execute(sa.text("SELECT to_regclass('aws_connections')")).scalar()
    if table is not None and not force:
        others = bind.execute(
            sa.text("SELECT count(*) FROM aws_connections WHERE aad_scope <> 'assistant'")
        ).scalar_one()
        legacy = bind.execute(
            sa.text("SELECT id FROM aws_connections WHERE aad_scope = 'assistant'")
        ).first()
        access = a.get("access") if isinstance(a.get("access"), dict) else DIRECT
        cid = a.get("connection_id")
        moved = (access.get("mode") or "direct") != "direct" or (
            cid is not None and (legacy is None or int(cid) != int(legacy[0]))
        )
        if others or moved:
            raise RuntimeError(
                "P4-1 downgrade refused: other AWS connections exist or the assistant uses "
                "another connection / a role hop (the 1.4.x settings would be stale). Move the "
                "assistant back to the 'Default' connection with direct access and delete the "
                "other connections, or set NETMON_FORCE_DOWNGRADE=1."
            )
    if a:
        bind.execute(
            sa.text(
                "UPDATE settings SET value = value - 'connection_id' - 'access' "
                "WHERE key = 'assistant'"
            )
        )
    op.execute("DROP TABLE IF EXISTS aws_connections")
