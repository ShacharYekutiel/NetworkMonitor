#!/usr/bin/env python3
"""Fake SSH network devices for the phase-3 config-backup tests (docs/architecture.md §13.11).

One asyncssh server process serves many device *personalities* on 127.0.0.x addresses (no root: any port,
default 8022). Each device emulates the CLI of one driver: banner, prompt, "Press any key" (ArubaOS), ANSI
escapes (ArubaOS), paging until the paging command was sent, the Cisco enable step, exec support or refusal,
`% Invalid input` for unknown commands, password and public-key auth, legacy-only algorithms, a hang after
login, a huge (9 MiB) output and host-key rotation.

    python tests/sim/ssh/fake_device.py --state-dir /tmp/sshlab --control-port 18622 --lab
    python tests/sim/ssh/fake_device.py --state-dir DIR --device cw1=comware@127.0.0.111:8022 \\
        --device old=arubaos_switch@127.0.0.119:8022,legacy-only --device h=comware@127.0.0.120:8022,hang-after-login

Device spec: NAME=PERSONALITY@ADDRESS:PORT[,flag...]; flags: legacy-only, legacy-strict, hang-after-login, huge,
v2. legacy-only = contract (group14-sha1 + ssh-rsa only; NOTE asyncssh offers both by default, so clients reach
it without any legacy flag); legacy-strict = group1-sha1 + aes128-cbc/3des-cbc + ssh-rsa only (old ArubaOS).
--lab starts the standard lab (LAB below). Prints "READY control=<port> devices=<n>" when listening.

Credentials (every device): user `netmon-backup`, password `Backup-pass-1`, Cisco enable password
`Enable-pass-1`; public-key auth with STATE_DIR/client_key (OpenSSH ed25519, generated at the first start; the
`.pub` is authorized on every device). All of them can be changed per device in the state file.

Per-device state (control file) STATE_DIR/<name>/state.json, re-read at every connection, so tests can also
edit it directly: {"version": "v1"|"v2", "hang": false, "huge": false, "username": ..., "password": ...,
"enable_password": ..., "authorized_keys": [...], "privileged_login": false, "exec": null (= personality)}.
Configs: configs/<personality config_dir>/<version>.txt with placeholders {{HOSTNAME}}, {{RAND}} (random
number, volatile) and {{NOW:<strftime>}} (current UTC time, volatile). The normalised expected configs (masking
on) are in expected/<personality>/<version>.txt (generated by expected.py).

Command log STATE_DIR/commands.jsonl (JSON lines, also GET /log): {"time", "device", "personality",
"address", "peer", "event", ...}; events: connect, auth_begin {username}, auth_password {username, ok},
auth_publickey {username, ok}, shell, exec {command}, command {command, privileged}, enable_password {ok}
(never the value), pre_prompt, page {answer}, disconnect. The read-only guarantee is asserted from the
`command`/`exec` events (allowed_commands()).

Control API (HTTP on 127.0.0.1:--control-port, JSON):
  GET    /health
  GET    /devices                         [{name, personality, driver, address, port, fingerprint, algorithm,
                                            public_key, flags, state}]
  GET    /devices/<name>
  POST   /devices/<name>/state            body merged into state.json (e.g. {"version": "v2"})
  POST   /devices/<name>/rotate-host-key  new host key, listener restarted -> {fingerprint, algorithm}
  POST   /devices/<name>/restore-host-key  back to the first key (key 0) -> {fingerprint, algorithm}
  POST   /devices/<name>/stop | /start    close / reopen the listener (connect_refused simulation)
  GET    /log[?device=NAME&event=command] the command log;  DELETE /log clears it
  GET    /client-key                      {"private_key": "...", "public_key": "..."}
"""

