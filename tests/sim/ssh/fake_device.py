import asyncssh
import yaml

HERE = Path(__file__).resolve().parent
PERSONALITIES = HERE / "personalities"
CONFIGS = HERE / "configs"

DEFAULT_USER = "netmon-backup"
DEFAULT_PASSWORD = "Backup-pass-1"
DEFAULT_ENABLE = "Enable-pass-1"
HUGE_BYTES = 9 * 1024 * 1024

# The standard lab (127.0.0.111-.121; the 2b-2 lab ends at .110). Port 8022 everywhere.
LAB = [
    ("sw-cw1", "comware", "127.0.0.111", []),
    ("sw-aos1", "arubaos_switch", "127.0.0.112", []),
    ("sw-cx1", "aruba_cx", "127.0.0.113", []),
    ("gw-hq", "checkpoint_clish", "127.0.0.114", []),
    ("gw-bash", "checkpoint_bash", "127.0.0.115", []),
    ("r1", "cisco_ios", "127.0.0.116", []),
    ("fgt1", "fortigate", "127.0.0.117", []),
    ("rb1", "mikrotik", "127.0.0.118", []),
    ("sw-legacy", "arubaos_switch", "127.0.0.119", ["legacy-only"]),
    ("sw-hang", "comware", "127.0.0.120", ["hang-after-login"]),
    ("rb-huge", "mikrotik", "127.0.0.121", ["huge"]),
    ("sw-legacy1", "arubaos_switch", "127.0.0.122", ["legacy-strict"]),
]

# Session-only setup commands and backup commands any shipped driver may send (data-model § [3] drivers),
# plus the session housekeeping the engine needs. Anything else in the log is a read-only violation.
ALLOWED_SETUP = {"screen-length disable", "no page", "terminal length 0", "terminal width 0",
                 "terminal pager 0", "set clienv rows 0"}
ALLOWED_BACKUP = {"display current-configuration", "show running-config", "show configuration",
                  'clish -c "show configuration"', "show full-configuration", "/export"}
ALLOWED_HOUSEKEEPING = {"", "exit", "quit", "logout", "enable"}


def allowed_commands() -> set[str]:
    return ALLOWED_SETUP | ALLOWED_BACKUP | ALLOWED_HOUSEKEEPING


ANSI_PRE_OUTPUT = "\x1b[1;24r\x1b[24;1H"
ANSI_PRE_PROMPT = "\x1b[24;1H\x1b[2K"
LEGACY_KEX = ["diffie-hellman-group14-sha1"]
LEGACY_HOSTKEY = ["ssh-rsa"]
# QA addition: asyncssh >= 2.14 still offers diffie-hellman-group14-sha1 and ssh-rsa BY DEFAULT, so a
# "legacy-only" device per the contract (group14-sha1 + ssh-rsa) is reachable without the legacy flag.
# "legacy-strict" emulates really old ArubaOS-Switch firmware: group1-sha1 + CBC ciphers + ssh-rsa only.
STRICT_KEX = ["diffie-hellman-group1-sha1"]
STRICT_CIPHERS = ["aes128-cbc", "3des-cbc"]


def now_iso() -> str:
    return datetime.now(UTC).isoformat(timespec="milliseconds").replace("+00:00", "Z")


def load_personality(name: str) -> dict:
    p = yaml.safe_load((PERSONALITIES / f"{name}.yaml").read_text())
    p["name"] = name
    p.setdefault("config_dir", name)
    p.setdefault("exec_crlf", name == "mikrotik")
    return p


def render_config(personality: dict, version: str, hostname: str) -> str:
    text = (CONFIGS / personality["config_dir"] / f"{version}.txt").read_text()
    now = datetime.now(UTC)
    text = text.replace("{{HOSTNAME}}", hostname).replace("{{RAND}}", str(random.randint(100000, 999999)))
    return re.sub(r"\{\{NOW:([^}]*)\}\}", lambda m: now.strftime(m.group(1)), text)


def huge_config() -> str:
    line = "interface GigabitEthernet1/0/{i}\n description huge-config-padding-line-{i:08d}\n"
    out, size, i = [], 0, 0
    while size < HUGE_BYTES:
        s = line.format(i=i)
        out.append(s)
        size += len(s)
        i += 1
    return "".join(out)


class Device:
    def __init__(self, lab: Lab, name: str, personality: str, address: str, port: int, flags: list[str]):
        self.lab = lab
        self.name = name
        self.p = load_personality(personality)
        self.address = address
        self.port = port
        self.flags = set(flags)
        self.dir = lab.state_dir / name
        self.dir.mkdir(parents=True, exist_ok=True)
        self.server: asyncio.AbstractServer | None = None
        self.key_index = 0
        self.strict = "legacy-strict" in self.flags
        self.legacy = "legacy-only" in self.flags or self.strict
        sf = self.dir / "state.json"
        if not sf.exists():
            st = {"version": "v2" if "v2" in self.flags else "v1", "hang": "hang-after-login" in self.flags,
                  "huge": "huge" in self.flags, "username": DEFAULT_USER, "password": DEFAULT_PASSWORD,
                  "enable_password": DEFAULT_ENABLE, "authorized_keys": [lab.client_pub],
                  "privileged_login": False, "exec": None, "hostname": name}
            sf.write_text(json.dumps(st, indent=2))
        idx = self.dir / "host_key_index"
        self.key_index = int(idx.read_text()) if idx.exists() else 0

    # ---------------------------------------------------------------- state / keys
    def state(self) -> dict:
        try:
            return json.loads((self.dir / "state.json").read_text())
        except (OSError, ValueError):
            return {}

    def update_state(self, patch: dict) -> dict:
        st = self.state()
        st.update(patch)
        (self.dir / "state.json").write_text(json.dumps(st, indent=2))
        return st

    def key_type(self) -> str:
        return "ssh-rsa" if self.legacy else self.p.get("host_key_type", "ssh-ed25519")

    def host_key(self) -> asyncssh.SSHKey:
        path = self.dir / f"host_key_{self.key_index}"
        if not path.exists():
            kt = self.key_type()
            key = asyncssh.generate_private_key(kt, key_size=2048) if kt == "ssh-rsa" else \
                asyncssh.generate_private_key(kt)
            key.write_private_key(str(path))
        return asyncssh.read_private_key(str(path))

    def info(self) -> dict:
        k = self.host_key()
        return {"name": self.name, "personality": self.p["name"], "driver": self.p["driver"],
                "address": self.address, "port": self.port, "algorithm": k.get_algorithm(),
                "fingerprint": k.get_fingerprint("sha256"),
                "public_key": k.export_public_key("openssh").decode().strip(),
                "flags": sorted(self.flags), "listening": self.server is not None, "state": self.state()}

    async def start(self) -> None:
        if self.server is not None:
            return
        opts: dict = {}
        if self.strict:
            opts.update(kex_algs=STRICT_KEX, encryption_algs=STRICT_CIPHERS, signature_algs=LEGACY_HOSTKEY)
        elif self.legacy:
            opts.update(kex_algs=LEGACY_KEX, signature_algs=LEGACY_HOSTKEY)
        self.server = await asyncssh.create_server(
            lambda: SimServer(self), self.address, self.port, server_host_keys=[self.host_key()],
            process_factory=self.handle, line_editor=False, encoding="utf-8", allow_scp=False,
            sftp_factory=None, agent_forwarding=False, x11_forwarding=False, keepalive_interval=0,
            login_timeout=60, **opts)

    async def stop(self) -> None:
        if self.server is not None:
            self.server.close()
            await self.server.wait_closed()
            self.server = None

    async def set_key(self, index: int) -> dict:
        self.key_index = index
        (self.dir / "host_key_index").write_text(str(index))
        await self.stop()
        await self.start()
        k = self.host_key()
        self.lab.log(self, "-", "host_key_rotated", fingerprint=k.get_fingerprint("sha256"), index=index)
        return {"fingerprint": k.get_fingerprint("sha256"), "algorithm": k.get_algorithm()}

    # ---------------------------------------------------------------- sessions
    async def handle(self, process: asyncssh.SSHServerProcess) -> None:
        conn = process.get_extra_info("connection")
        peer = conn.get_extra_info("peername")[0] if conn else "?"
        st = self.state()
        try:
            if process.command is not None:
                await self.handle_exec(process, peer, st)
            else:
                await self.handle_shell(process, peer, st)
        except (asyncssh.BreakReceived, asyncssh.TerminalSizeChanged):
            pass
        except (BrokenPipeError, ConnectionError, asyncssh.DisconnectError, asyncio.CancelledError):
            pass
        finally:
            try:
                process.exit(0)
            except Exception:  # noqa: BLE001
                pass

    def config_text(self, st: dict) -> str:
        if st.get("huge"):
            return huge_config()
        return render_config(self.p, st.get("version", "v1"), st.get("hostname", self.name))

    async def handle_exec(self, process: asyncssh.SSHServerProcess, peer: str, st: dict) -> None:
        cmd = process.command.strip()
        self.lab.log(self, peer, "exec", command=cmd)
        allow_exec = st.get("exec") if st.get("exec") is not None else self.p.get("exec", False)
        if st.get("hang"):
            await asyncio.sleep(3600)
            return
        if not allow_exec:
            process.stderr.write(self.p.get("exec_refusal", "exec not supported") + "\n")
            process.exit(1)
            return
        out = self.p.get("exec_commands", {}).get(cmd)
        if out is None:
            inv = self.p.get("exec_invalid", {"stderr": "invalid command\n", "status": 1})
            word = cmd.split()[0] if cmd.split() else ""
            if inv.get("stdout"):
                process.stdout.write(inv["stdout"].replace("{line}", cmd).replace("{word}", word))
            if inv.get("stderr"):
                process.stderr.write(inv["stderr"].replace("{line}", cmd).replace("{word}", word))
            process.exit(int(inv.get("status", 1)))
            return
        text = self.config_text(st) if out == "@config" else out
        if self.p.get("exec_crlf"):
            text = text.replace("\n", "\r\n")
        # write in chunks so a 9 MiB output streams
        for i in range(0, len(text), 65536):
            process.stdout.write(text[i : i + 65536])
            await process.stdout.drain()
        process.exit(0)

    async def handle_shell(self, process: asyncssh.SSHServerProcess, peer: str, st: dict) -> None:
        p = self.p
        self.lab.log(self, peer, "shell", term=process.get_terminal_type(), size=list(process.get_terminal_size()[:2]))
        reader = LineReader(process)
        ansi = bool(p.get("ansi"))
        w = process.stdout.write
        host = st.get("hostname", self.name)
        user = st.get("username", DEFAULT_USER)
        if p.get("banner"):
            w(p["banner"])
        if p.get("press_any_key"):
            w(("\x1b[2K" if ansi else "") + p["press_any_key"] + "\r\n")
            await reader.read_char()
            self.lab.log(self, peer, "pre_prompt")
            if ansi:
                w("\x1b[2J\x1b[?7l\x1b[3;23r\x1b[?6l\x1b[1;1H")
        if st.get("hang"):
            await asyncio.sleep(3600)
            return
        privileged = bool(st.get("privileged_login")) or not p.get("enable")
        paging = p.get("paging") is not None

        def prompt() -> str:
            base = p["enable"]["privileged_prompt"] if (p.get("enable") and privileged) else p["prompt"]
            return (ANSI_PRE_PROMPT if ansi else "") + base.replace("{hostname}", host).replace("{user}", user)

        w("\r\n" + prompt())
        while True:
            line = await reader.read_line()
            if line is None:
                break
            w(line + "\r\n")  # echo (PTY)
            cmd = " ".join(line.split())
            self.lab.log(self, peer, "command", command=cmd, privileged=privileged)
            low = cmd.lower()
            if low in ("exit", "quit", "logout"):
                w("\r\n")
                break
            if cmd == "":
                w(prompt())
                continue
            if p.get("enable") and low == p["enable"]["command"] and not privileged:
                w(p["enable"]["password_prompt"])
                pw = await reader.read_line()
                ok = pw is not None and pw == st.get("enable_password", DEFAULT_ENABLE)
                self.lab.log(self, peer, "enable_password", ok=ok)
                w("\r\n")
                if ok:
                    privileged = True
                else:
                    w(p["enable"].get("failure", "% Access denied\r\n"))
                w(prompt())
                continue
            if paging and low in [c.lower() for c in (p["paging"].get("disable") or [])]:
                paging = False
            out = None
            for k, v in (p.get("commands") or {}).items():
                if k.lower() == low:
                    out = v
                    break
            if out is not None and cmd in (p.get("privileged_only") or []) and not privileged:
                w(p.get("not_privileged", p["invalid"]))
                w(prompt())
                continue
            if out is None:
                word = cmd.split()[0]
                w(p["invalid"].replace("{line}", cmd).replace("{word}", word))
                w(prompt())
                continue
            text = self.config_text(st) if out == "@config" else out
            text = text.replace("\r\n", "\n").replace("\n", "\r\n")
            if ansi and text:
                w(ANSI_PRE_OUTPUT)
            if paging and text:
                if not await self.paged(process, reader, peer, text):
                    w("\r\n")
            else:
                for i in range(0, len(text), 65536):
                    w(text[i : i + 65536])
                    await process.stdout.drain()
            w(prompt())
        self.lab.log(self, peer, "disconnect")

    async def paged(self, process: asyncssh.SSHServerProcess, reader: LineReader, peer: str, text: str) -> bool:
        pg = self.p["paging"]
        n = int(pg.get("lines", 24))
        marker = pg.get("marker", "---- More ----")
        lines = text.split("\r\n")
        i = 0
        step = n
        while i < len(lines):
            chunk = lines[i : i + step]
            i += step
            process.stdout.write("\r\n".join(chunk) + ("\r\n" if i < len(lines) else ""))
            if i >= len(lines):
                return True
            process.stdout.write(marker)
            ch = await reader.read_char()
            self.lab.log(self, peer, "page", answer=repr(ch))
            process.stdout.write("\r" + " " * len(marker) + "\r")
            if ch in (None, "q", "Q", "\x03"):
                return False
            step = 1 if ch in ("\r", "\n") else n
        return True


class LineReader:
    def __init__(self, process: asyncssh.SSHServerProcess):
        self.process = process
        self.buf = ""
        self.skip_lf = False

    async def _fill(self) -> bool:
        try:
            data = await self.process.stdin.read(4096)
        except (asyncssh.BreakReceived, asyncssh.TerminalSizeChanged):
            return True
        if not data:
            return False
        self.buf += data
        return True

    async def read_char(self) -> str | None:
        while not self.buf:
            if not await self._fill():
                return None
        c, self.buf = self.buf[0], self.buf[1:]
        if c == "\n" and self.skip_lf:
            self.skip_lf = False
            return await self.read_char()
        self.skip_lf = c == "\r"
        return c

    async def read_line(self) -> str | None:
        out = []
        while True:
            c = await self.read_char()
            if c is None:
                return "".join(out) if out else None
            if c in ("\r", "\n"):
                return "".join(out)
            if c in ("\x7f", "\x08"):
                if out:
                    out.pop()
                continue
            out.append(c)


class SimServer(asyncssh.SSHServer):
    def __init__(self, dev: Device):
        self.dev = dev
        self.peer = "?"

    def connection_made(self, conn: asyncssh.SSHServerConnection) -> None:
        self.peer = conn.get_extra_info("peername")[0]
        self.dev.lab.log(self.dev, self.peer, "connect")

    def connection_lost(self, exc: Exception | None) -> None:
        pass

    def begin_auth(self, username: str) -> bool:
        self.dev.lab.log(self.dev, self.peer, "auth_begin", username=username)
        return True

    def password_auth_supported(self) -> bool:
        return True

    def validate_password(self, username: str, password: str) -> bool:
        st = self.dev.state()
        ok = username == st.get("username", DEFAULT_USER) and password == st.get("password", DEFAULT_PASSWORD)
        self.dev.lab.log(self.dev, self.peer, "auth_password", username=username, ok=ok)
        return ok

    def public_key_auth_supported(self) -> bool:
        return True

    def validate_public_key(self, username: str, key: asyncssh.SSHKey) -> bool:
        st = self.dev.state()
        mine = key.export_public_key("openssh").decode().split()[:2]
        ok = username == st.get("username", DEFAULT_USER) and any(
            a.split()[:2] == mine for a in st.get("authorized_keys", []))
        self.dev.lab.log(self.dev, self.peer, "auth_publickey", username=username, ok=ok)
        return ok

    def kbdint_auth_supported(self) -> bool:
        return False


class Lab:
    def __init__(self, state_dir: Path):
        self.state_dir = state_dir
        state_dir.mkdir(parents=True, exist_ok=True)
        self.log_path = state_dir / "commands.jsonl"
        self.devices: dict[str, Device] = {}
        ck = state_dir / "client_key"
        if not ck.exists():
            k = asyncssh.generate_private_key("ssh-ed25519", comment="netmon-qa")
            k.write_private_key(str(ck))
            k.write_public_key(str(ck) + ".pub")
            os.chmod(ck, 0o600)
        self.client_key = ck.read_text()
        self.client_pub = (state_dir / "client_key.pub").read_text().strip()

    def log(self, dev: Device, peer: str, event: str, **kw: object) -> None:
        rec = {"time": now_iso(), "device": dev.name, "personality": dev.p["name"], "address": dev.address,
               "peer": peer, "event": event, **kw}
        with self.log_path.open("a") as f:
            f.write(json.dumps(rec) + "\n")

    def read_log(self) -> list[dict]:
        if not self.log_path.exists():
            return []
        return [json.loads(x) for x in self.log_path.read_text().splitlines() if x.strip()]


# ---------------------------------------------------------------- control API (tiny HTTP/1.1)
async def control(lab: Lab, reader: asyncio.StreamReader, writer: asyncio.StreamWriter) -> None:
    try:
        head = await reader.readuntil(b"\r\n\r\n")
        lines = head.decode("latin-1").split("\r\n")
        method, target, _ = lines[0].split(" ", 2)
        headers = {k.lower(): v.strip() for k, v in (x.split(":", 1) for x in lines[1:] if ":" in x)}
        body = await reader.readexactly(int(headers.get("content-length", "0") or 0))
        code, obj = await route(lab, method, target, json.loads(body) if body.strip() else {})
    except Exception as e:  # noqa: BLE001
        code, obj = 500, {"error": f"{type(e).__name__}: {e}"}
    data = json.dumps(obj).encode()
    writer.write(f"HTTP/1.1 {code} X\r\nContent-Type: application/json\r\nContent-Length: {len(data)}\r\n"
                 f"Connection: close\r\n\r\n".encode() + data)
    await writer.drain()
    writer.close()


async def route(lab: Lab, method: str, target: str, body: dict) -> tuple[int, object]:
    u = urlsplit(target)
    q = {k: v[0] for k, v in parse_qs(u.query).items()}
    parts = [x for x in u.path.split("/") if x]
    if parts == ["health"]:
        return 200, {"ok": True, "devices": len(lab.devices)}
    if parts == ["client-key"]:
        return 200, {"private_key": lab.client_key, "public_key": lab.client_pub}
    if parts == ["log"]:
        if method == "DELETE":
            lab.log_path.write_text("")
            return 200, {"ok": True}
        items = lab.read_log()
        if "device" in q:
            items = [x for x in items if x["device"] == q["device"]]
        if "event" in q:
            items = [x for x in items if x["event"] == q["event"]]
        return 200, items
    if parts == ["allowed-commands"]:
        return 200, sorted(allowed_commands())
    if parts and parts[0] == "devices":
        if len(parts) == 1:
            return 200, [d.info() for d in lab.devices.values()]
        dev = lab.devices.get(parts[1])
        if dev is None:
            return 404, {"error": "unknown device"}
        if len(parts) == 2:
            return 200, dev.info()
        action = parts[2]
        if method != "POST":
            return 405, {"error": "POST"}
        if action == "state":
            return 200, dev.update_state(body)
        if action == "rotate-host-key":
            return 200, await dev.set_key(dev.key_index + 1)
        if action == "restore-host-key":
            return 200, await dev.set_key(0)
        if action == "stop":
            await dev.stop()
            return 200, {"ok": True}
        if action == "start":
            await dev.start()
            return 200, {"ok": True}
    return 404, {"error": "not found"}


def parse_device(spec: str) -> tuple[str, str, str, int, list[str]]:
    m = re.match(r"^([\w.\-]+)=(\w+)@([\d.]+):(\d+)((?:,[\w\-]+)*)$", spec)
    if not m:
        raise SystemExit(f"bad --device {spec!r} (NAME=PERSONALITY@ADDR:PORT[,flag...])")
    flags = [f for f in m.group(5).split(",") if f]
    return m.group(1), m.group(2), m.group(3), int(m.group(4)), flags


async def amain(a: argparse.Namespace) -> None:
    lab = Lab(Path(a.state_dir))
    specs = [parse_device(s) for s in a.device]
    if a.lab:
        specs += [(n, p, ip, a.port, f) for n, p, ip, f in LAB]
    for name, pers, ip, port, flags in specs:
        lab.devices[name] = Device(lab, name, pers, ip, port, flags)
    for d in lab.devices.values():
        await d.start()
    srv = await asyncio.start_server(lambda r, w: control(lab, r, w), "127.0.0.1", a.control_port)
    port = srv.sockets[0].getsockname()[1]
    (lab.state_dir / "control_port").write_text(str(port))
    print(f"READY control={port} devices={len(lab.devices)}", flush=True)
    for d in lab.devices.values():
        i = d.info()
        print(f"  {d.name:<10} {d.p['name']:<17} {d.address}:{d.port} {i['algorithm']} {i['fingerprint']} "
              f"{','.join(sorted(d.flags))}", flush=True)
    await asyncio.Event().wait()


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--state-dir", required=True)
    ap.add_argument("--control-port", type=int, default=0)
    ap.add_argument("--device", action="append", default=[])
    ap.add_argument("--lab", action="store_true", help="start the standard lab (127.0.0.111-.121)")
    ap.add_argument("--port", type=int, default=8022, help="SSH port of the --lab devices")
    a = ap.parse_args()
    if not a.lab and not a.device:
        ap.error("--lab and/or --device")
    import logging
    logging.getLogger("asyncssh").setLevel(logging.WARNING)
    try:
        asyncio.run(amain(a))
    except KeyboardInterrupt:
        pass


if __name__ == "__main__":
    sys.exit(main())
