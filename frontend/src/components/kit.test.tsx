import { describe, expect, it, vi } from 'vitest';
import { fireEvent, render, screen } from '@testing-library/react';
import '../i18n';
import {
  AiTag,
  Banner,
  CitationChip,
  EmptyState,
  OptionCard,
  ProgressCard,
  WizardSteps,
} from './kit';

describe('premium v2 kit', () => {
  it('empty and error blocks', () => {
    render(
      <EmptyState title="Nothing yet" error>
        Try again
      </EmptyState>,
    );
    expect(screen.getByRole('alert')).toHaveTextContent('Nothing yet');
  });

  it('wizard steps: done steps are buttons that go back, the current one is marked', () => {
    const go = vi.fn();
    render(<WizardSteps label="steps" steps={['One', 'Two', 'Three']} current={1} onGo={go} />);
    fireEvent.click(screen.getByRole('button', { name: /One/ }));
    expect(go).toHaveBeenCalledWith(0);
    expect(screen.getByText('Two').closest('li')).toHaveAttribute('aria-current', 'step');
    expect(screen.queryByRole('button', { name: /Three/ })).toBeNull();
  });

  it('banner, option card, citation, AI tag, progress', () => {
    const pick = vi.fn();
    render(
      <>
        <Banner tone="down" title="Failed" />
        <OptionCard name="o" value="a" checked={false} onChange={pick} title="Option A" />
        <CitationChip n={2} label="source 2" />
        <AiTag fine />
        <ProgressCard title="Pausing" done={3} total={3} />
      </>,
    );
    expect(screen.getByRole('alert')).toHaveTextContent('Failed');
    fireEvent.click(screen.getByRole('radio'));
    expect(pick).toHaveBeenCalledWith('a');
    expect(screen.getByRole('button', { name: 'source 2' })).toHaveTextContent('2');
    expect(screen.getByText(/Generated by AI/)).toBeTruthy();
    expect(screen.getByText('3 / 3')).toBeTruthy();
  });
});
